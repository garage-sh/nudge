import type { DestinationWithGeneratedSecrets, DestinationView } from '@nudge/shared';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { failure, startPipeline, type DashboardClient, type Pipeline } from './harness/index.js';

describe('A Project’s Destinations from the dashboard', () => {
  let pipeline: Pipeline;
  let member: DashboardClient;

  beforeAll(async () => {
    pipeline = await startPipeline();
    member = await pipeline.signIn();
  });

  afterAll(async () => {
    await pipeline?.stop();
  });

  const webhook = (url = 'https://receiver.test/nudge') => ({
    type: 'webhook',
    name: 'Internal receiver',
    config: { url },
    filter: { types: ['bug'], minimumSeverity: 'major' },
  });

  async function create(projectId: string, body: unknown = webhook()) {
    const response = await member.post<DestinationWithGeneratedSecrets>(
      `/api/projects/${projectId}/destinations`,
      body,
    );
    expect(response.status).toBe(201);
    return response.body;
  }

  it('adds, lists, updates then deletes a webhook Destination', async () => {
    const { project } = await pipeline.createProject({ name: 'Shop' });

    const { destination, generatedSecrets } = await create(project.id);

    expect(destination).toEqual({
      id: expect.any(String),
      projectId: project.id,
      name: 'Internal receiver',
      type: 'webhook',
      config: { url: 'https://receiver.test/nudge' },
      filter: { types: ['bug'], minimumSeverity: 'major' },
      state: 'active',
      secrets: ['signingSecret'],
      createdAt: expect.any(String),
    });
    // The signing secret, generated by the Instance, is only shown at creation.
    expect(generatedSecrets.signingSecret).toMatch(/^[\w-]{40,}$/);
    expect(await member.get(`/api/projects/${project.id}/destinations`)).toEqual({
      status: 200,
      body: [destination],
    });

    const update = await member.patch<DestinationView>(`/api/destinations/${destination.id}`, {
      name: 'Receiver v2',
      config: { url: 'https://other.test/hook' },
      filter: { types: ['question', 'bug'], minimumSeverity: null },
    });
    const updated = {
      ...destination,
      name: 'Receiver v2',
      config: { url: 'https://other.test/hook' },
      filter: { types: ['bug', 'question'], minimumSeverity: null },
    };
    expect(update).toEqual({ status: 200, body: updated });
    expect(await member.get(`/api/destinations/${destination.id}`)).toEqual({
      status: 200,
      body: updated,
    });

    expect((await member.delete(`/api/destinations/${destination.id}`)).status).toBe(204);
    expect(await member.get(`/api/projects/${project.id}/destinations`)).toEqual({
      status: 200,
      body: [],
    });
    expect((await member.get(`/api/destinations/${destination.id}`)).status).toBe(404);
  });

  it('encrypts secrets in the database and never returns them', async () => {
    const { project } = await pipeline.createProject({ name: 'Secrets' });
    const { destination, generatedSecrets } = await create(project.id);
    const secret = generatedSecrets.signingSecret!;

    const row = await pipeline.destinationRow(destination.id);
    expect(row?.encryptedSecrets).toMatch(/^v1:/);
    expect(JSON.stringify(row)).not.toContain(secret);
    const read = await member.get(`/api/destinations/${destination.id}`);
    const list = await member.get(`/api/projects/${project.id}/destinations`);
    expect(JSON.stringify([read.body, list.body])).not.toContain(secret);
  });

  it('adds a Discord channel: the webhook URL, which carries its token, is a validated secret', async () => {
    const { project } = await pipeline.createProject({ name: 'Discord' });
    const token = 'channel-token-3d89bb7572e0fb30d8128367b3b1b44f';
    const channel = (url?: string) => ({
      type: 'discord',
      name: 'Channel #bugs',
      config: {},
      ...(url === undefined ? {} : { secrets: { url } }),
    });

    for (const url of [
      undefined,
      'https://hooks.slack.com/services/T000/B000/XXXX',
      'http://discord.com/api/webhooks/223704706495545344/token',
      'https://discord.com/api/webhooks/223704706495545344/token?thread_id=1',
      'https://discord.com.trap.test/api/webhooks/223704706495545344/token',
    ]) {
      const refusal = await member.post(`/api/projects/${project.id}/destinations`, channel(url));
      expect(refusal).toMatchObject({
        status: 400,
        body: {
          error: 'invalid_request',
          details: [{ path: expect.stringMatching(/^secrets/) }],
        },
      });
    }

    const { destination, generatedSecrets } = await create(
      project.id,
      channel(`https://discord.com/api/webhooks/223704706495545344/${token}`),
    );
    expect(destination).toMatchObject({ type: 'discord', config: {}, secrets: ['url'] });
    expect(generatedSecrets).toEqual({});
    const row = await pipeline.destinationRow(destination.id);
    expect(JSON.stringify(row)).not.toContain(token);
    const renamed = await member.patch<DestinationView>(`/api/destinations/${destination.id}`, {
      name: 'Channel #support',
    });
    expect(renamed.body).toMatchObject({ name: 'Channel #support', secrets: ['url'] });
    expect(JSON.stringify(renamed.body)).not.toContain(token);
  });

  it('adds a Linear team: the API key is a secret, the team and labels are validated', async () => {
    const { project } = await pipeline.createProject({ name: 'Linear' });
    const key = 'lin_api_9f8e7d6c5b4a39281706f5e4d3c2b1a0';
    const team = (config: unknown, secrets?: unknown) => ({
      type: 'linear',
      name: 'Linear ENG',
      config,
      ...(secrets === undefined ? {} : { secrets }),
    });
    const labels = { types: { bug: ' Bug ' }, severities: { blocking: 'Urgent' } };

    for (const [body, path] of [
      [team({ team: 'ENG', labels }), /^secrets/],
      [team({ team: 'ENG', labels }, { apiKey: '  ' }), /^secrets/],
      [team({ team: 'ENG-1', labels }, { apiKey: key }), /^config\.team/],
      [
        team({ team: 'ENG', labels: { types: { bugg: 'Bug' } } }, { apiKey: key }),
        /^config\.labels/,
      ],
      [team({ team: 'ENG', labels: { types: { bug: '' } } }, { apiKey: key }), /^config\.labels/],
    ] as const) {
      const refusal = await member.post(`/api/projects/${project.id}/destinations`, body);
      expect(refusal).toMatchObject({
        status: 400,
        body: { error: 'invalid_request', details: [{ path: expect.stringMatching(path) }] },
      });
    }

    const { destination, generatedSecrets } = await create(
      project.id,
      team({ team: 'eng', labels }, { apiKey: key }),
    );
    expect(destination).toMatchObject({
      type: 'linear',
      config: {
        team: 'ENG',
        labels: { types: { bug: 'Bug' }, severities: { blocking: 'Urgent' } },
      },
      secrets: ['apiKey'],
    });
    expect(generatedSecrets).toEqual({});
    const row = await pipeline.destinationRow(destination.id);
    expect(JSON.stringify(row)).not.toContain(key);
    const withoutLabels = await member.patch<DestinationView>(
      `/api/destinations/${destination.id}`,
      {
        config: { team: 'OPS' },
      },
    );
    expect(withoutLabels.body).toMatchObject({
      config: { team: 'OPS', labels: { types: {}, severities: {} } },
      secrets: ['apiKey'],
    });
    expect(JSON.stringify(withoutLabels.body)).not.toContain(key);
  });

  it('adds a Slack channel: the incoming webhook URL, which carries its token, is a validated secret', async () => {
    const { project } = await pipeline.createProject({ name: 'Slack' });
    const token = 'Xk9fT2qLm8Rv4sWz7Yb3Nc6D';
    const slackChannel = (url?: string) => ({
      type: 'slack',
      name: 'Channel #bugs',
      config: {},
      ...(url === undefined ? {} : { secrets: { url } }),
    });

    for (const url of [
      undefined,
      'https://discord.com/api/webhooks/223704706495545344/token',
      'http://hooks.slack.com/services/T00000000/B00000000/XXXX',
      'https://hooks.slack.com/services/T00000000/B00000000/XXXX?channel=general',
      'https://hooks.slack.com.trap.test/services/T00000000/B00000000/XXXX',
      'https://hooks.slack.com/triggers/T00000000/123/abc',
    ]) {
      const refusal = await member.post(
        `/api/projects/${project.id}/destinations`,
        slackChannel(url),
      );
      expect(refusal).toMatchObject({
        status: 400,
        body: {
          error: 'invalid_request',
          details: [{ path: expect.stringMatching(/^secrets/) }],
        },
      });
    }

    const { destination, generatedSecrets } = await create(
      project.id,
      slackChannel(`https://hooks.slack.com/services/T0A1B2C3D/B0E4F5G6H/${token}`),
    );
    expect(destination).toMatchObject({ type: 'slack', config: {}, secrets: ['url'] });
    expect(generatedSecrets).toEqual({});
    const row = await pipeline.destinationRow(destination.id);
    expect(JSON.stringify(row)).not.toContain(token);
  });

  it('adds a GitHub repository: the token is a secret, the owner/repo repository is validated', async () => {
    const { project } = await pipeline.createProject({ name: 'GitHub' });
    const token = 'github_pat_11ABCDEFG0123456789_abcdefghijklmnopqrstuvwxyz';
    const repo = (config: unknown, secrets?: unknown) => ({
      type: 'github',
      name: 'Issues shop-web',
      config,
      ...(secrets === undefined ? {} : { secrets }),
    });

    for (const [body, path] of [
      [repo({ repository: 'shop-inc/shop-web' }), /^secrets/],
      [repo({ repository: 'shop-inc/shop-web' }, { token: '  ' }), /^secrets/],
      [repo({ repository: 'shop-web' }, { token }), /^config\.repository/],
      [
        repo({ repository: 'https://github.com/shop-inc/shop-web' }, { token }),
        /^config\.repository/,
      ],
      [repo({ repository: '-shop/shop-web' }, { token }), /^config\.repository/],
      [repo({ repository: 'shop-inc/..' }, { token }), /^config\.repository/],
      [repo({ repository: 'shop-inc/shop-web', labels: {} }, { token }), /^config/],
    ] as const) {
      const refusal = await member.post(`/api/projects/${project.id}/destinations`, body);
      expect(refusal).toMatchObject({
        status: 400,
        body: { error: 'invalid_request', details: [{ path: expect.stringMatching(path) }] },
      });
    }

    const { destination, generatedSecrets } = await create(
      project.id,
      repo({ repository: ' shop-inc/shop-web ' }, { token }),
    );
    expect(destination).toMatchObject({
      type: 'github',
      config: { repository: 'shop-inc/shop-web' },
      secrets: ['token'],
    });
    expect(generatedSecrets).toEqual({});
    const row = await pipeline.destinationRow(destination.id);
    expect(JSON.stringify(row)).not.toContain(token);
  });

  it('undecryptable secrets (changed Instance key) prevent neither listing nor regenerating', async () => {
    const { project } = await pipeline.createProject({ name: 'Changed key' });
    const { destination } = await create(project.id);
    await pipeline.makeSecretsUndecryptable(destination.id);

    expect(await member.get(`/api/projects/${project.id}/destinations`)).toEqual({
      status: 200,
      body: [{ ...destination, secrets: [] }],
    });
    const renamed = await member.patch(`/api/destinations/${destination.id}`, { name: 'Renamed' });
    expect(renamed.status).toBe(200);
    const regeneration = await member.post<DestinationWithGeneratedSecrets>(
      `/api/destinations/${destination.id}/generated-secrets`,
    );
    expect(regeneration.status).toBe(201);
    expect(regeneration.body.destination.secrets).toEqual(['signingSecret']);
  });

  it('regenerates the signing secret and shows the new one only once', async () => {
    const { project } = await pipeline.createProject({ name: 'Rotation' });
    const { destination, generatedSecrets } = await create(project.id);

    const regeneration = await member.post<DestinationWithGeneratedSecrets>(
      `/api/destinations/${destination.id}/generated-secrets`,
    );

    expect(regeneration.status).toBe(201);
    expect(regeneration.body.destination).toEqual(destination);
    expect(regeneration.body.generatedSecrets.signingSecret).toMatch(/^[\w-]{40,}$/);
    expect(regeneration.body.generatedSecrets.signingSecret).not.toBe(
      generatedSecrets.signingSecret,
    );
  });

  it('"test" sends a sample Feedback through the adapter and returns the result, without a Delivery', async () => {
    const { project } = await pipeline.createProject({ name: 'Trial' });
    const { destination } = await create(project.id);
    const fake = pipeline.fakeDestination(destination.id);

    const delivered = await member.post(`/api/destinations/${destination.id}/test`);

    expect(delivered).toEqual({
      status: 200,
      body: { status: 'delivered', externalUrl: expect.stringContaining('https://') },
    });
    expect(fake.deliveries).toHaveLength(1);
    expect(fake.deliveries[0]).toMatchObject({
      isTest: true,
      project: { id: project.id, name: 'Trial' },
      feedback: { text: expect.stringContaining('Sample') },
    });
    expect(await pipeline.readFeedback(fake.deliveries[0]!.feedback.id)).toBeNull();

    fake.scriptSends(failure('auth', 'token refused'), new Error('ECONNREFUSED'));
    expect((await member.post(`/api/destinations/${destination.id}/test`)).body).toEqual({
      status: 'failed',
      failureClass: 'auth',
      message: 'token refused',
    });
    expect((await member.post(`/api/destinations/${destination.id}/test`)).body).toEqual({
      status: 'failed',
      failureClass: 'transient',
      message: 'ECONNREFUSED',
    });
    expect((await member.get(`/api/destinations/${destination.id}`)).body).toMatchObject({
      state: 'active',
    });
  });

  it.each([
    ['an unknown type', { ...webhook(), type: 'pigeon' }, 'type'],
    ['a URL that is not http(s)', webhook('ftp://recepteur.test'), 'config.url'],
    ['a URL with credentials', webhook('https://me:secret@recepteur.test'), 'config.url'],
    ['a URL with a password', webhook('https://:secret@recepteur.test'), 'config.url'],
    [
      'an unknown config field',
      { ...webhook(), config: { url: 'https://a.test', x: 1 } },
      'config',
    ],
    ['a secret the type does not know', { ...webhook(), secrets: { token: 'x' } }, 'secrets'],
    [
      'a Filter without a Type',
      { ...webhook(), filter: { types: [], minimumSeverity: null } },
      'filter.types',
    ],
    [
      'an unknown Severity',
      { ...webhook(), filter: { types: ['bug'], minimumSeverity: 'serious' } },
      'filter.minimumSeverity',
    ],
  ])('refuses %s', async (_case, body, path) => {
    const { project } = await pipeline.createProject({ name: 'Refusal' });

    const response = await member.post<{ error: string; details: { path: string }[] }>(
      `/api/projects/${project.id}/destinations`,
      body,
    );

    expect(response.status).toBe(400);
    expect(response.body.error).toBe('invalid_request');
    expect(response.body.details.map((d) => d.path)).toContainEqual(
      expect.stringMatching(new RegExp(`^${path.replace('.', '\\.')}`)),
    );
  });

  it('refuses an invalid update without changing anything', async () => {
    const { project } = await pipeline.createProject({ name: 'Refused update' });
    const { destination } = await create(project.id);

    const response = await member.patch(`/api/destinations/${destination.id}`, {
      config: { url: 'not a url' },
    });

    expect(response.status).toBe(400);
    expect((await member.get(`/api/destinations/${destination.id}`)).body).toEqual(destination);
  });

  it('404 for an unknown Project or Destination, 401 without a session', async () => {
    const unknown = '00000000-0000-4000-8000-000000000000';
    expect(await member.post(`/api/projects/${unknown}/destinations`, webhook())).toMatchObject({
      status: 404,
      body: { error: 'project_not_found' },
    });
    expect(await member.get(`/api/projects/${unknown}/destinations`)).toMatchObject({
      status: 404,
      body: { error: 'project_not_found' },
    });
    for (const response of [
      await member.get(`/api/destinations/${unknown}`),
      await member.patch(`/api/destinations/not-an-id`, { name: 'x' }),
      await member.delete(`/api/destinations/${unknown}`),
      await member.post(`/api/destinations/${unknown}/test`),
    ]) {
      expect(response).toMatchObject({ status: 404, body: { error: 'destination_not_found' } });
    }
    const { project } = await pipeline.createProject({ name: 'Anonymous' });
    expect(
      (await pipeline.dashboard().get(`/api/projects/${project.id}/destinations`)).status,
    ).toBe(401);
  });
});
