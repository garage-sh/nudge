import {
  isDestinationType,
  FILTER_ALL,
  DESTINATION_TYPES,
  type DestinationView,
  type FilterView,
  type DestinationTestResult,
} from '@nudge/shared';
import { useEffect, useRef, useState } from 'react';
import { useParams } from 'react-router';
import {
  useCreateDestination,
  useDeleteDestination,
  useDestinations,
  useRegenerateGeneratedSecrets,
  useTestDestination,
  useUpdateDestination,
} from '../../api/destinations.js';
import { useProject } from '../../api/projects.js';
import { useT, type Messages } from '../../i18n/index.js';
import {
  ConfirmAction,
  CopyableValue,
  EmptyState,
  ErrorMessage,
  ExternalLink,
  Loading,
  useReturnFocus,
} from '../../layout/ui.js';
import { ProjectHeader, ProjectNotFound } from '../Project.js';
import { DestinationStatePill, SeverityGauge } from '../feedback-badges.js';
import { DestinationForm } from './DestinationForm.js';
import { RoutingMap } from './RoutingMap.js';
import { formOf, DESTINATION_FORMS, TypeIcon } from './types/index.js';

/** Secrets generated by the Instance, shown only once after creation or regeneration. */
export interface ShownSecrets {
  readonly type: string;
  readonly name: string;
  readonly secrets: Readonly<Record<string, string>>;
}

/** Shows the secrets a creation or a regeneration has just generated. */
type ShowSecrets = (
  destination: DestinationView,
  secrets: Readonly<Record<string, string>>,
) => void;

export function Destinations() {
  const t = useT();
  const projectId = useParams().id ?? '';
  const project = useProject(projectId);
  const destinations = useDestinations(projectId);
  const [shownSecrets, setShownSecrets] = useState<ShownSecrets | null>(null);
  const [adding, setAdding] = useState(false);
  const [added, setAdded] = useState<string | null>(null);
  if (project.isPending || destinations.isPending) return <Loading />;
  if (project.isError) {
    return <ProjectNotFound error={project.error} onRetry={() => void project.refetch()} />;
  }
  if (destinations.isError) {
    return (
      <section>
        <ProjectHeader project={project.data} />
        <ErrorMessage error={destinations.error} onRetry={() => void destinations.refetch()} />
      </section>
    );
  }
  const show: ShowSecrets = (destination, secrets) =>
    setShownSecrets(
      Object.keys(secrets).length > 0
        ? { type: destination.type, name: destination.name, secrets }
        : null,
    );
  const none = destinations.data.length === 0;
  // Without a Destination, the add form is the only thing to do: it is open.
  const formOpen = adding || none;

  return (
    <section>
      <ProjectHeader
        project={project.data}
        actions={
          formOpen ? null : (
            <button type="button" onClick={() => setAdding(true)}>
              {t.destinations.add}
            </button>
          )
        }
      />
      <p className="help tab-intro">{t.destinations.intro}</p>
      {shownSecrets ? <GeneratedSecrets {...shownSecrets} /> : null}
      {/* Empty: why it matters, then the form that fills it. */}
      {none ? (
        <EmptyState title={t.destinations.emptyTitle}>{t.destinations.emptyHelp}</EmptyState>
      ) : null}
      {formOpen ? (
        <AddDestination
          projectId={projectId}
          show={show}
          onAdded={(id) => {
            setAdded(id);
            setAdding(false);
          }}
          onCancel={none ? undefined : () => setAdding(false)}
        />
      ) : null}
      {none ? null : <RoutingMap destinations={destinations.data} />}
      {none ? null : (
        <ul className="list destinations">
          {destinations.data.map((destination) => (
            <li key={destination.id}>
              <DestinationRow
                destination={destination}
                show={show}
                focus={destination.id === added}
              />
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}

export function GeneratedSecrets({ type, name, secrets }: ShownSecrets) {
  const t = useT();
  const descriptions: Readonly<
    Partial<Record<string, (t: Messages) => { label: string; help: string }>>
  > = formOf(type)?.generatedSecrets ?? {};
  return (
    <div className="warning panel" role="status">
      <p>{t.destinations.copySecretNow(name)}</p>
      {Object.entries(secrets).map(([key, value]) => {
        const description = descriptions[key]?.(t);
        return (
          <div key={key}>
            <h3>{description?.label ?? key}</h3>
            {description ? <p className="help">{description.help}</p> : null}
            <CopyableValue label={description?.label ?? key} value={value} />
          </div>
        );
      })}
    </div>
  );
}

/** The Filter, readable: the accepted types, and the Severity threshold as a gauge. */
function FilterSummary({ filter: { types, minimumSeverity } }: { filter: FilterView }) {
  const t = useT();
  return (
    <p className="destination-filter">
      <span>{types.map((type) => t.labels.feedbackType[type]).join(', ')}</span>
      {minimumSeverity ? (
        <SeverityGauge
          severity={minimumSeverity}
          label={t.destinations.severityOrMore(t.labels.severity[minimumSeverity])}
        />
      ) : (
        <span>{t.destinations.anySeverity}</span>
      )}
    </p>
  );
}

function DestinationRow({
  destination,
  show,
  focus = false,
}: {
  destination: DestinationView;
  show: ShowSecrets;
  /** The Destination was just added: its name takes focus. */
  focus?: boolean;
}) {
  const t = useT();
  const [editing, setEditing] = useState(false);
  const edit = useReturnFocus(editing);
  const title = useRef<HTMLHeadingElement>(null);
  useEffect(() => {
    if (focus) title.current?.focus();
  }, [focus]);
  const form = formOf(destination.type);
  const update = useUpdateDestination(destination.projectId, destination.id);
  const deletion = useDeleteDestination(destination.projectId, destination.id);
  const regeneration = useRegenerateGeneratedSecrets(destination.projectId, destination.id);
  const test = useTestDestination(destination.id);

  if (editing && isDestinationType(destination.type)) {
    return (
      <DestinationForm
        title={t.destinations.editTitle(destination.name)}
        initial={{ ...destination, type: destination.type, config: { ...destination.config } }}
        typeEditable={false}
        savedSecrets={destination.secrets}
        submitLabel={t.common.save}
        pending={update.isPending}
        error={update.error}
        onCancel={() => setEditing(false)}
        onSubmit={({ name, config, filter, secrets }) =>
          update.mutate(
            { name, config, filter, ...(secrets ? { secrets } : {}) },
            { onSuccess: () => setEditing(false) },
          )
        }
      />
    );
  }

  const generatedSecrets = form ? Object.values(form.generatedSecrets) : [];
  return (
    <article className="destination" data-state={destination.state}>
      <div className="destination-row">
        <div className="destination-name">
          <h2 ref={title} tabIndex={-1}>
            {destination.name}
          </h2>
          <p>
            <span className="destination-type">
              <TypeIcon icon={form?.icon} />
              {form?.label ?? destination.type}
            </span>
            {form ? (
              <span className="destination-target">{form.summary(destination.config, t)}</span>
            ) : null}
          </p>
        </div>
        <FilterSummary filter={destination.filter} />
        <DestinationStatePill state={destination.state} />
      </div>
      {destination.state === 'suspended' ? (
        <p className="problem">{t.destinations.suspendedProblem}</p>
      ) : null}
      <div className="actions">
        <button
          type="button"
          className="secondary"
          disabled={test.isPending}
          onClick={() => test.mutate()}
        >
          {t.common.test}
        </button>
        {form ? (
          <button ref={edit} type="button" className="secondary" onClick={() => setEditing(true)}>
            {t.common.edit}
          </button>
        ) : null}
        {generatedSecrets.length > 0 ? (
          <ConfirmAction
            label={t.destinations.regenerate(
              generatedSecrets.map((describe) => describe(t).label.toLowerCase()).join(', '),
            )}
            question={t.destinations.regenerateQuestion}
            pending={regeneration.isPending}
            onConfirm={() =>
              regeneration.mutate(undefined, {
                onSuccess: (result) => show(result.destination, result.generatedSecrets),
              })
            }
          />
        ) : null}
        <ConfirmAction
          label={t.common.delete}
          question={t.destinations.deleteQuestion}
          pending={deletion.isPending}
          onConfirm={() => deletion.mutate()}
        />
      </div>
      {test.data ? <TestResult result={test.data} /> : null}
      <ErrorMessage error={test.error ?? regeneration.error ?? deletion.error} />
    </article>
  );
}

/** The "Test" button's result; `delivered`: what was delivered (a sample Feedback, a sample alert). */
export function TestResult({
  result,
  delivered,
}: {
  result: DestinationTestResult;
  delivered?: string;
}) {
  const t = useT();
  if (result.status === 'delivered') {
    return (
      <p role="status">
        {delivered ?? t.destinations.testDelivered}
        {result.externalUrl ? (
          <>
            {' '}
            <ExternalLink href={result.externalUrl} />
          </>
        ) : null}
      </p>
    );
  }
  return (
    <p role="status" className="alert">
      {t.destinations.testFailed(t.labels.failureClass[result.failureClass], result.message)}
    </p>
  );
}

function AddDestination({
  projectId,
  show,
  onAdded,
  onCancel,
}: {
  projectId: string;
  show: ShowSecrets;
  onAdded: (id: string) => void;
  onCancel?: () => void;
}) {
  const t = useT();
  const creation = useCreateDestination(projectId);
  const type = DESTINATION_TYPES[0];
  return (
    <DestinationForm
      title={t.destinations.add}
      initial={{
        type,
        name: '',
        config: { ...DESTINATION_FORMS[type].initialConfig },
        filter: FILTER_ALL,
      }}
      typeEditable
      submitLabel={t.destinations.add}
      pending={creation.isPending}
      error={creation.error}
      onCancel={onCancel}
      onSubmit={(values) =>
        creation.mutate(values, {
          onSuccess: (result) => {
            show(result.destination, result.generatedSecrets);
            onAdded(result.destination.id);
          },
        })
      }
    />
  );
}
