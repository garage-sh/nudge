import { randomBytes } from 'node:crypto';
import { BadRequestException } from '@nestjs/common';
import { SecretDecryptionError } from '@nudge/core';
import type { DestinationSecrets } from '@nudge/database';
import {
  DESTINATION_DEFINITIONS,
  isDestinationType,
  type ApiErrorBody,
  type DestinationDefinition,
} from '@nudge/shared';
import { z } from 'zod';
import { parseBody } from '../../validation.js';

/**
 * What depends on a Destination's type (config, entered or generated secrets), shared
 * by the Projects' Destinations and the Instance's Alert destination.
 */

/**
 * Undecryptable secrets (Instance key changed) count as "no secret": the Destination
 * stays listed and editable, the Member enters or regenerates its secrets again.
 */
export function readableSecrets(decrypt: () => DestinationSecrets): Record<string, string> {
  try {
    return { ...decrypt() };
  } catch (error) {
    if (error instanceof SecretDecryptionError) return {};
    throw error;
  }
}

/** A Destination whose type this Instance no longer serves cannot be changed. */
export function definitionOf(type: string): DestinationDefinition {
  if (isDestinationType(type)) return DESTINATION_DEFINITIONS[type];
  const refusal: ApiErrorBody = { error: 'unknown_destination_type' };
  throw new BadRequestException(refusal);
}

/** Config and secrets per the type's schema; a refusal names `config.…` or `secrets.…`. */
export function validateByType(
  definition: DestinationDefinition,
  values: { config: unknown; secrets: unknown },
): { config: Record<string, unknown>; secrets: DestinationSecrets } {
  return parseBody(
    z.strictObject({ config: definition.config, secrets: definition.secrets }),
    values,
  );
}

/**
 * Applies an input's secrets to the stored entered secrets: a value replaces, `null`
 * clears, an absent key keeps the stored secret.
 */
export function applyEnteredSecrets(
  stored: Record<string, string>,
  input: Readonly<Record<string, string | null>> = {},
): Record<string, string> {
  const result = { ...stored };
  for (const [name, value] of Object.entries(input)) {
    if (value === null) delete result[name];
    else result[name] = value;
  }
  return result;
}

export function generateSecrets(definition: DestinationDefinition): Record<string, string> {
  return Object.fromEntries(
    definition.generatedSecrets.map((name) => [name, randomBytes(32).toString('base64url')]),
  );
}

/** Secrets generated by the Instance on one side, entered by the Member on the other. */
export function splitSecrets(
  definition: DestinationDefinition,
  secrets: DestinationSecrets,
): { generated: Record<string, string>; entered: Record<string, string> } {
  const generated: Record<string, string> = {};
  const entered: Record<string, string> = {};
  for (const [name, value] of Object.entries(secrets)) {
    if (definition.generatedSecrets.includes(name)) generated[name] = value;
    else entered[name] = value;
  }
  return { generated, entered };
}
