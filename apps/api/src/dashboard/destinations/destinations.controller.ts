import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  Param,
  Patch,
  Post,
  UseGuards,
} from '@nestjs/common';
import {
  destinationUpdateSchema,
  newDestinationSchema,
  type DestinationWithGeneratedSecrets,
  type DestinationView,
  type DestinationTestResult,
} from '@nudge/shared';
import { SessionGuard } from '../auth/session.guard.js';
import { parseBody } from '../../validation.js';
import { DestinationsService } from './destinations.service.js';

@Controller('api')
@UseGuards(SessionGuard)
export class DestinationsController {
  constructor(private readonly destinations: DestinationsService) {}

  @Get('projects/:projectId/destinations')
  list(@Param('projectId') projectId: string): Promise<DestinationView[]> {
    return this.destinations.list(projectId);
  }

  /** 201 with the secrets generated by the Instance (signing secret), readable this one time. */
  @Post('projects/:projectId/destinations')
  create(
    @Param('projectId') projectId: string,
    @Body() body: unknown,
  ): Promise<DestinationWithGeneratedSecrets> {
    return this.destinations.create(projectId, parseBody(newDestinationSchema, body));
  }

  @Get('destinations/:id')
  read(@Param('id') id: string): Promise<DestinationView> {
    return this.destinations.read(id);
  }

  @Patch('destinations/:id')
  update(@Param('id') id: string, @Body() body: unknown): Promise<DestinationView> {
    return this.destinations.update(id, parseBody(destinationUpdateSchema, body));
  }

  @Delete('destinations/:id')
  @HttpCode(204)
  delete(@Param('id') id: string): Promise<void> {
    return this.destinations.delete(id);
  }

  @Post('destinations/:id/generated-secrets')
  regenerateGeneratedSecrets(@Param('id') id: string): Promise<DestinationWithGeneratedSecrets> {
    return this.destinations.regenerateGeneratedSecrets(id);
  }

  /** Sends a sample Feedback; 200 with the result, delivered or failed. */
  @Post('destinations/:id/test')
  @HttpCode(200)
  test(@Param('id') id: string): Promise<DestinationTestResult> {
    return this.destinations.test(id);
  }
}
